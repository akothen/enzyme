#!/usr/bin/env python3
"""Emit a Makefile fragment of per-case `axon` targets from `eval/sizes.json`
(a file target + phony alias per case, plus CASES_<kernel>, CASE_TARGETS, and
the LNC1_TARGETS / LNC2_TARGETS split by each case's `lnc` key).
Each recipe carries the case fully on the command line (--sizes, optional
--dtype, and for head-to-head cases --rtol/--atol), so `axon` never reads
sizes.json at run time. The case id is the `--out` stem (out/<target>.csv).
`_`-prefixed keys are skipped; the Makefile redirects stdout to size_targets.mk."""

import json
from pathlib import Path

SIZES_JSON = Path(__file__).parent / "sizes.json"
KERNELS_DIR = Path(__file__).parent.parent / "kernels"


def _kernel_path(kernel: str) -> str:
    """The spec path for a kernel: `kernels/<name>/` (package dir, make-prereq'd
    on its files) or the classic `kernels/<name>.py`."""
    if (KERNELS_DIR / kernel / "__init__.py").is_file():
        return f"kernels/{kernel}"
    return f"kernels/{kernel}.py"


def main() -> None:
    data = json.loads(SIZES_JSON.read_text())

    all_cases: list[str] = []
    lnc1_cases: list[str] = []
    lnc2_cases: list[str] = []
    blocks: list[str] = []

    for kernel in sorted(k for k in data if not k.startswith("_")):
        cases = data[kernel]
        kernel_cases: list[str] = []
        for case_id, cfg in cases.items():
            if case_id.startswith("_"):
                continue
            target = f"{kernel}_{case_id}"
            kernel_cases.append(target)
            all_cases.append(target)
            # An "lnc" key (2) marks the sharding search; absent ⇒ lnc=1.
            (lnc2_cases if cfg.get("lnc") == 2 else lnc1_cases).append(target)

            sizes = " ".join(str(s) for s in cfg["sizes"])
            dtype = f" --dtype {cfg['dtype']}" if "dtype" in cfg else ""
            # Presence of rtol/atol marks a head-to-head case: forward the
            # tolerances so `axon` needs no sizes.json at run time.
            tols = ""
            if "rtol" in cfg and "atol" in cfg:
                tols = f" --rtol {cfg['rtol']} --atol {cfg['atol']}"
            # An "lnc" key (2) opts the case into the sharding search; absent ⇒
            # lnc=1 (today's single-core path).
            lnc = f" --lnc {cfg['lnc']}" if "lnc" in cfg else ""
            kpath = _kernel_path(kernel)
            # For a package dir, depend on its .py files (a directory's own
            # mtime only tracks entry add/remove, not edits).
            prereq = f"$(wildcard {kpath}/*.py)" if not kpath.endswith(".py") else kpath
            # Only a head-to-head case (rtol+atol present) exports a winner, so
            # only those have anything to specialize. lnc=2 is excluded: the SPMD
            # sharding path is not a shipped deliverable, so `winners/` holds
            # single-core kernels only. The `-` prefix keeps a specialize failure
            # from failing a bench that already succeeded, and the tool is
            # stdlib-only, so it needs no venv.
            specialize = (
                f"\t-python3 tools/specialize_winner.py {target}\n"
                if tols and cfg.get("lnc") != 2
                else ""
            )
            blocks.append(
                f"out/{target}.csv: {prereq} eval/sizes.json\n"
                f"\taxon $(AXON_ARGS) {kpath} "
                f"--sizes {sizes}{dtype}{tols}{lnc} --out $@\n"
                f"{specialize}"
                f"\n"
                f"{target}: out/{target}.csv\n"
            )
        blocks.append(f"CASES_{kernel} := {' '.join(kernel_cases)}\n")

    print("# Generated by eval/gen_size_targets.py from eval/sizes.json.")
    print("# Do not edit by hand; regenerated by the Makefile.")
    print()
    print("\n".join(blocks))
    print(f"CASE_TARGETS := {' '.join(all_cases)}")
    print(f"LNC1_TARGETS := {' '.join(lnc1_cases)}")
    print(f"LNC2_TARGETS := {' '.join(lnc2_cases)}")


if __name__ == "__main__":
    main()
